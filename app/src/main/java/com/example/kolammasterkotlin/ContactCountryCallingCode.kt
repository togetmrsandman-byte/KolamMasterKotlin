internal val defaultContactCountryCallingCode: ContactCountryCallingCode =
    contactCountryCallingCodes.first { it.countryCode == "IN" }

internal fun isValidLocalContactPhone(phone: String): Boolean =
    phone.isNotEmpty() && phone.all { it in '0'..'9' }

internal fun digitsOnlyLocalContactPhoneInput(value: String): String =
    value.filter { it in '0'..'9' }

internal fun isValidContactPhoneForSubmission(phone: String): Boolean =
    phone.isBlank() ||
        isValidContactPhone(phone) ||
        phone.matches(Regex("^\\+[0-9]+$"))

internal fun internationalContactPhone(
    country: ContactCountryCallingCode,
    localNumber: String
): String = country.callingCode + localNumber
