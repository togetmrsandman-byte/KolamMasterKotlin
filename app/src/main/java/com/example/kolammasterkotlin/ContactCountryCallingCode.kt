internal fun ContactCountryCallingCode.flagEmoji(): String =
    countryCode
        .takeIf { it.length == 2 && it.all(Char::isLetter) }
        ?.uppercase()
        ?.map { character ->
            String(Character.toChars(0x1F1E6 + character.code - 'A'.code))
        }
        ?.joinToString("")
        ?: ""

